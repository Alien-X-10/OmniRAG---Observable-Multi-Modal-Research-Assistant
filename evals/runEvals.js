const ai = new GoogleGenAI({
  apiKey: process.env.GEMINI_API_KEY,
  apiVersion: 'v1beta',
  httpOptions: { apiVersion: 'v1beta' },
});

// Primary Judge Model (with automatic fallback if preview/regional alias differs)
const JUDGE_MODELS = [
  'gemini-3.1-flash-lite',
  'gemini-3.1-flash-lite-preview',
  'gemini-2.5-flash',
];

const PASS_THRESHOLD = Number(process.env.EVAL_PASS_THRESHOLD || 1.0);

const JUDGE_RESPONSE_SCHEMA = {
  type: Type.OBJECT,
  properties: {
    factual_score: {
      type: Type.NUMBER,
      description:
        'Score from 0.0 to 1.0 measuring how accurately the candidate answer captures the ground truth without contradiction.',
    },
    passed: {
      type: Type.BOOLEAN,
      description: 'True if factual_score >= 0.8 and there are no fabricated claims.',
    },
    reasoning: {
      type: Type.STRING,
      description: 'Concise 1-sentence explanation of the grade.',
    },
  },
  required: ['factual_score', 'passed', 'reasoning'],
};

/**
 * Invokes Gemini 3.1 Flash-Lite as an impartial LLM-as-a-Judge
 * to grade the RAG output against the golden ground truth.
 */
async function evaluateWithJudge({ question, groundTruth, candidateAnswer }) {
  const prompt = `You are a strict FAANG CI/CD Evaluation Judge.
Compare the Candidate Answer generated by our RAG pipeline against the Ground Truth Answer.

Question: "${question}"
Ground Truth Answer: "${groundTruth}"
Candidate Answer: "${candidateAnswer}"

Grading Rules:
1. Ignore inline citation tags like <chunk id="..."> when judging factual equivalence.
2. Score 1.0 if the Candidate Answer states the core technical mechanism in the Ground Truth Answer without adding unsupported claims.
3. Score 0.0 if the Candidate Answer contradicts the Ground Truth or hallucinates facts.`;

  let lastError = null;
  for (const modelName of JUDGE_MODELS) {
    try {
      const response = await ai.models.generateContent({
        model: modelName,
        contents: [{ role: 'user', parts: [{ text: prompt }] }],
        config: {
          temperature: 0.0,
          responseMimeType: 'application/json',
          responseSchema: JUDGE_RESPONSE_SCHEMA,
        },
      });

      const verdict = JSON.parse(response.text);
      return { ...verdict, judge_model: modelName };
    } catch (err) {
      lastError = err;
    }
  }

  throw new Error(`Judge evaluation failed across models: ${lastError?.message}`);
}

/**
 * Evaluates a single test case from evals/golden_dataset.json
 */
async function evaluateTestCase(testCase) {
  const {
    query_id,
    category,
    question,
    expected_abstain,
    expected_citations,
    ground_truth_answer,
  } = testCase;

  const { output, telemetry } = await generateGroundedAnswer(question, {
    topK: 5,
  });

  // 1. Verify strict schema & inline citation contract
  validateLLMOutput(output);

  // 2. Check Abstention Contract
  if (output.is_abstained !== expected_abstain) {
    return {
      query_id,
      category,
      passed: false,
      score: 0.0,
      reason: `Abstention mismatch: expected is_abstained=${expected_abstain}, got ${output.is_abstained}`,
      latency_ms: telemetry.totalLatencyMs,
    };
  }

  // If the test case expects abstention and the model properly abstained -> 100% Pass
  if (expected_abstain === true) {
    return {
      query_id,
      category,
      passed: true,
      score: 1.0,
      judge_model: 'deterministic_abstention_gate',
      reason: 'System properly abstained on out-of-scope adversarial query.',
      latency_ms: telemetry.totalLatencyMs,
    };
  }

  // 3. Check Expected Citations
  const actualChunkIds = new Set((output.citations || []).map((c) => c.chunk_id));
  const missingCitations = (expected_citations || []).filter(
    (cid) => !actualChunkIds.has(cid)
  );

  if (missingCitations.length > 0) {
    return {
      query_id,
      category,
      passed: false,
      score: 0.0,
      reason: `Missing required citations: ${missingCitations.join(', ')}`,
      latency_ms: telemetry.totalLatencyMs,
    };
  }

  // 4. Grade Factual Accuracy with LLM-as-a-Judge (Gemini 3.1 Flash-Lite)
  const judgeResult = await evaluateWithJudge({
    question,
    groundTruth: ground_truth_answer,
    candidateAnswer: output.answer,
  });

  return {
    query_id,
    category,
    passed: Boolean(judgeResult.passed && judgeResult.factual_score >= 0.8),
    score: Number(judgeResult.factual_score),
    judge_model: judgeResult.judge_model,
    reason: judgeResult.reasoning,
    latency_ms: telemetry.totalLatencyMs,
  };
}

/**
 * Main Evaluation Suite Runner
 */
export async function runEvaluationSuite() {
  const datasetPath = path.join(__dirname, 'golden_dataset.json');
  const rawDataset = await fs.readFile(datasetPath, 'utf-8');
  const goldenDataset = JSON.parse(rawDataset);

  console.log(`\n============================================================`);
  console.log(
    `[CI/CD Eval Gate] Running ${goldenDataset.length} Golden Dataset cases...`
  );
  console.log(`============================================================`);

  const results = [];
  for (const testCase of goldenDataset) {
    console.log(`\n-> Evaluating [${testCase.query_id}] (${testCase.category})...`);
    const outcome = await evaluateTestCase(testCase);
    results.push(outcome);

    const badge = outcome.passed ? 'PASS' : 'FAIL';
    console.log(
      `   [${badge}] Score: ${outcome.score.toFixed(2)} | Judge: ${
        outcome.judge_model || 'N/A'
      } | Latency: ${outcome.latency_ms}ms`
    );
    console.log(`   Reason: ${outcome.reason}`);
  }

  const passedCount = results.filter((r) => r.passed).length;
  const passRate = passedCount / results.length;

  console.log(`\n============================================================`);
  console.log(
    `[Eval Gate Summary] Passed: ${passedCount}/${results.length} (${(
      passRate * 100
    ).toFixed(1)}%) | Required Threshold: ${(PASS_THRESHOLD * 100).toFixed(1)}%`
  );
  console.log(`============================================================\n`);

  if (passRate < PASS_THRESHOLD) {
    console.error(
      `[CI/CD BLOCKED] Pass rate ${(passRate * 100).toFixed(
        1
      )}% is below required threshold ${(PASS_THRESHOLD * 100).toFixed(1)}%.`
    );
    process.exitCode = 1;
  } else {
    console.log('[CI/CD APPROVED] All quality gates passed. Safe to deploy.');
  }

  return { passRate, results };
}

if (process.argv[1] && process.argv[1].endsWith('runEvals.js')) {
  runEvaluationSuite()
    .catch((err) => {
      console.error('[Eval Suite Error]:', err.message);
      process.exitCode = 1;
    })
    .finally(() => closeDB());
}